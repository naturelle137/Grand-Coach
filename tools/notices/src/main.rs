//! Writes `THIRD-PARTY-NOTICES`: the licence texts and copyright notices of
//! every third-party crate in `Cargo.lock` (D-43).
//!
//! Run `cargo run --locked -p notices` after each `Cargo.lock` change. It
//! reads the published crate sources, so run `cargo fetch --locked` first.

use std::collections::{BTreeMap, BTreeSet};
use std::error::Error;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::{env, fs};

use serde_json::Value;

type Result<T> = std::result::Result<T, Box<dyn Error>>;

const OUTPUT: &str = "THIRD-PARTY-NOTICES";

/// Standard texts used when a crate ships no licence file, in order of
/// preference.
const STANDARD_TEXTS: [(&str, &str); 3] = [
    ("MIT", include_str!("../licenses/MIT.txt")),
    ("Apache-2.0", include_str!("../licenses/Apache-2.0.txt")),
    ("BSL-1.0", include_str!("../licenses/BSL-1.0.txt")),
];

/// File name prefixes (lower case) of licence and notice files.
const LICENCE_FILES: [&str; 6] = [
    "license",
    "licence",
    "copying",
    "notice",
    "copyright",
    "unlicense",
];

const HEADER: &str = "\
Third-party notices for Grand-Coach
===================================

Grand-Coach is licensed under the EUPL-1.2, its card faces and texts under
CC BY-SA 4.0. Its builds contain third-party crates and fonts whose licences
require the copyright notices and licence texts below to accompany every
copy. This file covers every third-party crate in Cargo.lock for all target
platforms, including crates only needed to build or test. Where a crate
offers a choice of licences, all texts it ships are listed; Grand-Coach uses
it under the licences permitted by its policy (D-42).

Generated by `cargo run --locked -p notices` (tools/notices); do not edit.
";

struct Crate {
    name: String,
    version: String,
    license: String,
    authors: Vec<String>,
    repository: Option<String>,
    dir: PathBuf,
}

fn main() -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let cargo = env::var("CARGO").unwrap_or_else(|_| "cargo".to_owned());
    let output = Command::new(cargo)
        .args(["metadata", "--format-version", "1", "--locked"])
        .current_dir(&root)
        .output()?;
    if !output.status.success() {
        return Err(String::from_utf8_lossy(&output.stderr).into());
    }
    let metadata: Value = serde_json::from_slice(&output.stdout)?;
    let mut crates = metadata["packages"]
        .as_array()
        .ok_or("cargo metadata lists no packages")?
        .iter()
        .filter(|package| !package["source"].is_null())
        .map(parse)
        .collect::<Result<Vec<_>>>()?;
    crates.sort_by(|a, b| (&a.name, &a.version).cmp(&(&b.name, &b.version)));
    fs::write(root.join(OUTPUT), render(&crates)?)?;
    println!("wrote {OUTPUT} ({} crates)", crates.len());
    Ok(())
}

fn parse(package: &Value) -> Result<Crate> {
    let text = |key: &str| package[key].as_str().map(str::to_owned);
    let name = text("name").ok_or("package without name")?;
    let license = text("license").ok_or_else(|| format!("{name} has no licence expression"))?;
    let manifest = text("manifest_path").ok_or_else(|| format!("{name} has no manifest"))?;
    Ok(Crate {
        version: text("version").ok_or_else(|| format!("{name} has no version"))?,
        license,
        authors: package["authors"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .map(str::to_owned)
            .collect(),
        repository: text("repository"),
        dir: Path::new(&manifest)
            .parent()
            .ok_or("manifest without directory")?
            .to_owned(),
        name,
    })
}

fn render(crates: &[Crate]) -> Result<String> {
    let mut out = String::from(HEADER);
    writeln!(out, "\nContents\n--------\n")?;
    for c in crates {
        writeln!(out, "- {} {} ({})", c.name, c.version, c.license)?;
    }

    // Identical texts are printed once and referenced afterwards.
    let mut first_seen: BTreeMap<String, String> = BTreeMap::new();
    let mut standard: BTreeSet<&str> = BTreeSet::new();
    for c in crates {
        writeln!(out, "\n\n== {} {} ==\n", c.name, c.version)?;
        writeln!(out, "Licence: {}", c.license)?;
        if !c.authors.is_empty() {
            writeln!(out, "Authors: {}", c.authors.join(", "))?;
        }
        if let Some(repository) = &c.repository {
            writeln!(out, "Repository: {repository}")?;
        }
        let files = licence_files(&c.dir)?;
        if !files.iter().any(|(file, _)| !file.contains('/')) {
            let (id, _) = STANDARD_TEXTS
                .iter()
                .find(|(id, _)| mentions(&c.license, id))
                .ok_or_else(|| {
                    format!("{} ships no licence file and no standard text fits", c.name)
                })?;
            standard.insert(id);
            let holders = if c.authors.is_empty() {
                format!("the {} authors", c.name)
            } else {
                c.authors.join(", ")
            };
            writeln!(
                out,
                "\nThe published crate contains no licence file. It is used under\n\
                 {id}; the standard text in the appendix applies, copyright holders:\n\
                 {holders}."
            )?;
        }
        for (file, text) in files {
            if let Some(first) = first_seen.get(&text) {
                writeln!(out, "\n--- {file}: same text as {first} ---")?;
            } else {
                writeln!(out, "\n--- {file} ---\n\n{text}")?;
                first_seen.insert(text, format!("{file} of {} {}", c.name, c.version));
            }
        }
    }

    if !standard.is_empty() {
        writeln!(out, "\n\n== Appendix: standard licence texts ==")?;
        for (id, text) in STANDARD_TEXTS {
            if standard.contains(id) {
                writeln!(out, "\n--- {id} ---\n\n{}", normalize(text))?;
            }
        }
    }
    Ok(out)
}

/// Licence and notice files in the crate root, plus the font licences that
/// `epaint_default_fonts` ships in `fonts/`, as (relative path, text).
fn licence_files(dir: &Path) -> Result<Vec<(String, String)>> {
    let mut files = Vec::new();
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        let name = file_name(&path);
        let lower = name.to_lowercase();
        if path.is_file() && LICENCE_FILES.iter().any(|p| lower.starts_with(p)) {
            files.push((name, read(&path)?));
        }
    }
    let fonts = dir.join("fonts");
    if fonts.is_dir() {
        for entry in fs::read_dir(fonts)? {
            let path = entry?.path();
            if path.extension().is_some_and(|ext| ext == "txt") {
                files.push((format!("fonts/{}", file_name(&path)), read(&path)?));
            }
        }
    }
    files.sort();
    Ok(files)
}

fn file_name(path: &Path) -> String {
    path.file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_default()
}

fn read(path: &Path) -> Result<String> {
    Ok(normalize(&String::from_utf8_lossy(&fs::read(path)?)))
}

/// Unix line ends, tabs as spaces, no trailing whitespace or blank edges.
fn normalize(text: &str) -> String {
    let lines: Vec<String> = text
        .trim_start_matches('\u{feff}')
        .lines()
        .map(|line| line.replace('\t', "    ").trim_end().to_owned())
        .collect();
    let start = lines.iter().position(|l| !l.is_empty()).unwrap_or(0);
    let end = lines
        .iter()
        .rposition(|l| !l.is_empty())
        .map_or(0, |i| i + 1);
    lines[start..end.max(start)].join("\n")
}

/// Whether the SPDX expression names the licence `id`.
fn mentions(expression: &str, id: &str) -> bool {
    expression
        .split(|c: char| c.is_whitespace() || matches!(c, '(' | ')' | '/'))
        .any(|token| token == id)
}
